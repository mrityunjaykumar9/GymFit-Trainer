/*
 * The gym equipment of the current exercise in 3D: bars, plates, dumbbells, benches, cable towers, mats.
 * The side-view animation data describes props as 2D lines / discs; here each becomes a real object with sensible
 * depth. Everything is made from a handful of pooled, instanced primitive meshes (assets/models/props, generated by
 * tools/athlete_model/build_props.py) that are re-positioned every frame.
 */

internal enum class Kind(val file: String, val pool: Int) {
    CYL_CHROME("cyl_chrome", 24), CYL_STEEL("cyl_steel", 32), CYL_BLACK("cyl_black", 16),
    CYL_PLATE("cyl_plate", 16), CYL_ACCENT("cyl_accent", 40),
    BOX_PAD("box_pad", 8), BOX_STEEL("box_steel", 12), BOX_MAT("box_mat", 2), SPHERE_STEEL("sphere_steel", 8)
}

/** One piece of equipment for one frame. Cylinders run a -> b with [r] radius; boxes are centred with a size. */
internal sealed class Prim(val kind: Kind) {
    class Cyl(kind: Kind, val a: V3, val b: V3, val r: Float) : Prim(kind)
    class Box(kind: Kind, val c: V3, val q: Q, val size: V3) : Prim(kind)
    class Ball(kind: Kind, val c: V3, val r: Float) : Prim(kind)
}

internal class PropKit(
    private val engine: Engine,
    private val scene: Scene,
    private val loader: AssetLoader,
    private val resources: ResourceLoader,
    read: (String) -> ByteBuffer?
) {
    private class Slot(val root: Int, val entities: IntArray, var active: Boolean = false)

    private val tm = engine.transformManager
    private val assets = ArrayList<FilamentAsset>()
    private val pools = HashMap<Kind, List<Slot>>()
    private val matrix = FloatArray(16)

    init {
        for (kind in Kind.values()) {
            val buf = read("models/props/${kind.file}.glb") ?: continue
            val instances = arrayOfNulls<FilamentInstance>(kind.pool)
            val asset = loader.createInstancedAsset(buf, instances) ?: continue
            resources.loadResources(asset)
            asset.releaseSourceData()
            assets += asset
            pools[kind] = instances.filterNotNull().map { Slot(it.root, it.entities) }
        }
    }

    fun update(motion: MotionDef, sk: Skeleton, poser: AthletePoser, mat: FloatArray?, exerciseName: String?) {
        val used = HashMap<Kind, Int>()
        for (prim in PropBuilder.build(motion, sk, poser, mat, exerciseName)) {
            val slots = pools[prim.kind] ?: continue
            val n = used.getOrDefault(prim.kind, 0)
            if (n >= slots.size) continue
            used[prim.kind] = n + 1
            val slot = slots[n]
            place(slot, prim)
            if (!slot.active) { scene.addEntity(slot.root); scene.addEntities(slot.entities); slot.active = true }
        }
        for ((kind, slots) in pools) {
            for (i in used.getOrDefault(kind, 0) until slots.size) {
                val s = slots[i]
                if (s.active) { scene.removeEntity(s.root); scene.removeEntities(s.entities); s.active = false }
            }
        }
    }

    private fun place(slot: Slot, p: Prim) {
        val ti = tm.getInstance(slot.root)
        when (p) {
            is Prim.Cyl -> {
                val d = p.b - p.a
                val len = max(d.len(), 1e-4f)
                tm.setTransform(ti, composeMatrix(V3.lerp(p.a, p.b, 0.5f), Q.fromTo(V3.Y, d), p.r * 2f, len, p.r * 2f, matrix))
            }
            is Prim.Box -> tm.setTransform(ti, composeMatrix(p.c, p.q, p.size.x, p.size.y, p.size.z, matrix))
            is Prim.Ball -> tm.setTransform(ti, composeMatrix(p.c, Q.IDENTITY, p.r * 2f, p.r * 2f, p.r * 2f, matrix))
        }
    }

    fun destroy() {
        for (pool in pools.values) for (s in pool) if (s.active) { scene.removeEntity(s.root); scene.removeEntities(s.entities) }
        for (a in assets) loader.destroyAsset(a)
        assets.clear(); pools.clear()
    }
}

/** Turns a [MotionDef]'s 2D props into 3D primitives for the current frame. */
internal object PropBuilder {
    private const val S = AthletePoser.SCALE

    /** Thickness of the exercise mat (m); the body is kept above this. */
    const val MAT_TOP = 0.016f

    /** True when the exercise is done on a mat (the 2D data draws it as a flat line on the floor). */
    fun hasMat(motion: MotionDef): Boolean = motion.props.any { p ->
        p is Prop.Line && p.a.joint == null && p.b.joint == null && p.a.y < 0.06f && p.b.y < 0.06f
    }

    /** [mat] = minX, maxX, minZ, maxZ the body reaches over the whole movement (model space), so limbs never leave the mat. */
    fun build(motion: MotionDef, sk: Skeleton, poser: AthletePoser, mat: FloatArray?, exerciseName: String?): List<Prim> {
        val out = ArrayList<Prim>(32)
        val ctx = Ctx(motion, sk, poser, mat, exerciseName?.let { exerciseSlug(it) } ?: "")
        val dumbbellJoints = motion.props.filterIsInstance<Prop.Dumbbell>().mapNotNull { it.at.joint }.toSet()
        for (p in motion.props) when (p) {
            is Prop.Line -> line(p, ctx, out)
            is Prop.Plate -> barbell(p, ctx, out)
            is Prop.Dumbbell -> dumbbell(p, ctx, dumbbellJoints, out)
            is Prop.Cable -> cable(p, ctx, out)
            is Prop.Circle -> circle(p, ctx, out)
            is Prop.RopeLoop -> rope(p, ctx, out)
        }
        return out
    }

    private class Ctx(val motion: MotionDef, val sk: Skeleton, val poser: AthletePoser, val mat: FloatArray?, val slug: String) {
        fun pos(name: String): V3 = poser.position(name)
        fun grip(side: String): V3 = pos("hand_$side") + poser.worldRotation("hand_$side").rotate(V3(0f, 0.055f, 0f))
        /** The way a handle runs through a closed hand (the axis the fingers wrap around). */
        fun handAxis(joint: String?): V3 = when (joint) {
            "wristN" -> poser.handleAxis("r")
            "wristF" -> poser.handleAxis("l")
            else -> V3.X
        }.let { if (it.x < 0f) -it else it }.unit(V3.X)

        val gripN get() = grip("r")
        val gripF get() = grip("l")

        /** Where a joint of the 2D skeleton is on the 3D body (model space). */
        fun joint(name: String): V3 = when (name) {
            "wristN" -> gripN; "wristF" -> gripF
            "elbowN" -> pos("lowerarm_r"); "elbowF" -> pos("lowerarm_l")
            "kneeN" -> pos("calf_r"); "kneeF" -> pos("calf_l")
            "ankleN" -> pos("foot_r"); "ankleF" -> pos("foot_l")
            "toeN" -> pos("ball_r"); "toeF" -> pos("ball_l")
            "shoulder" -> V3.lerp(pos("upperarm_r"), pos("upperarm_l"), 0.5f)
            "head" -> pos("Head") + V3(0f, 0.08f, 0f)
            else -> V3.lerp(pos("thigh_r"), pos("thigh_l"), 0.5f)     // "hip"
        }

        fun ref(r: Ref): V3 {
            val off = poser.dirToModel(V3(r.x, r.y, 0f)) * S
            return if (r.joint == null) off else joint(r.joint) + off
        }

        /** Average x (pose units) of the near hand over the whole movement: where an overhead bar is gripped. */
        val meanHandX: Float by lazy {
            var sum = 0f
            for (i in 0 until 12) sum += motion.skeletonAt(i / 12f).wristN.x
            sum / 12f
        }
    }

    private fun mirrorJoint(j: String): String? = when {
        j.endsWith("N") -> j.dropLast(1) + "F"
        j.endsWith("F") -> j.dropLast(1) + "N"
        else -> null
    }

    private fun boxAlong(kind: Kind, a: V3, b: V3, width: Float, thick: Float, out: MutableList<Prim>) {
        val d = b - a
        out += Prim.Box(kind, V3.lerp(a, b, 0.5f), Q.fromTo(V3.Y, d), V3(width, d.len(), thick))
    }

    // ------------------------------------------------------------------------------------------ lines

    private fun line(p: Prop.Line, c: Ctx, out: MutableList<Prim>) {
        val a = c.ref(p.a); val b = c.ref(p.b)
        val pinnedA = p.a.joint != null; val pinnedB = p.b.joint != null
        val metal = p.role == "metal"
        val thick = p.w * S
        val lenM = (b - a).len()
        when {
            // flat line on the floor = exercise mat, sized to everything the body reaches so no limb leaves it
            !pinnedA && !pinnedB && a.y < 0.06f * S && b.y < 0.06f * S -> {
                val m = c.mat
                val spanX = if (m != null) m[1] - m[0] else 0f
                val spanZ = if (m != null) m[3] - m[2] else 0f
                val cx = if (m != null) (m[0] + m[1]) / 2f else 0f
                val cz = if (m != null) (m[2] + m[3]) / 2f else V3.lerp(a, b, 0.5f).z
                val centre = V3(cx, MAT_TOP / 2f, cz)
                // long side along the line of the movement: front-to-back normally, side-to-side for frontal poses
                out += if (c.motion.frontal) Prim.Box(Kind.BOX_MAT, centre, Q.IDENTITY, V3(max(1.9f, spanX + 0.7f), MAT_TOP, max(0.9f, spanZ + 0.45f)))
                else Prim.Box(Kind.BOX_MAT, centre, Q.IDENTITY, V3(max(0.9f, spanX + 0.45f), MAT_TOP, max(1.9f, spanZ + 0.7f)))
            }
            // high horizontal metal line = pull-up frame: side rails + the bar that is actually gripped
            !pinnedA && !pinnedB && metal && p.w <= 0.025f && min(a.y, b.y) > 1.0f * S -> {
                for (sx in floatArrayOf(-0.5f, 0.5f)) out += Prim.Cyl(Kind.CYL_STEEL, V3(sx, a.y, a.z), V3(sx, b.y, b.z), 0.02f)
                val gz = c.meanHandX * S
                out += Prim.Cyl(Kind.CYL_CHROME, V3(-0.5f, a.y, gz), V3(0.5f, a.y, gz), 0.017f)
            }
            // pad / seat / back rest
            !metal && p.w >= 0.045f -> boxAlong(Kind.BOX_PAD, a, b, 0.30f, thick, out)
            // handles / levers fixed to the hands or feet
            metal && pinnedA && pinnedB && !(p.a.joint ?: "").startsWith("ankle") || (metal && pinnedA && pinnedB && p.w < 0.045f) -> {
                val feet = (p.a.joint ?: "").startsWith("ankle")
                for ((ra, rb) in listOf(p.a to p.b, mirrorRef(p.a) to mirrorRef(p.b))) {
                    val ma = c.ref(ra); val mb = c.ref(rb)
                    if (feet) boxAlong(Kind.BOX_STEEL, ma, mb, 0.14f, 0.03f, out)
                    else out += Prim.Cyl(Kind.CYL_CHROME, ma, mb, max(thick / 2f, 0.014f))
                }
            }
            metal && p.w >= 0.045f -> boxAlong(Kind.BOX_STEEL, a, b, 0.5f, thick, out)
            metal && (pinnedA || pinnedB) -> {
                // lever from a fixed pivot to the hands (T-bar row): end at the middle of the grip
                val hands = V3.lerp(c.gripN, c.gripF, 0.5f)
                val pivot = if (pinnedA) b else a
                out += Prim.Cyl(Kind.CYL_CHROME, pivot, hands, max(thick / 2f, 0.016f))
                out += Prim.Cyl(Kind.CYL_BLACK, hands + V3(-0.2f, 0f, 0f), hands + V3(0.2f, 0f, 0f), 0.017f)
            }
            // thin structural tube: a frame on each side of the athlete
            else -> {
                val x = if (max(a.y, b.y) > 1.2f * S) 0.5f else 0.14f
                for (sx in floatArrayOf(-x, x)) out += Prim.Cyl(Kind.CYL_STEEL, V3(sx, a.y, a.z), V3(sx, b.y, b.z), max(thick / 2f, 0.014f))
            }
        }
    }

    private fun mirrorRef(r: Ref): Ref = Ref(r.joint?.let { mirrorJoint(it) } ?: r.joint, r.x, r.y)

    // ------------------------------------------------------------------------------------- free weights

    private fun barbell(p: Prop.Plate, c: Ctx, out: MutableList<Prim>) {
        // The bar runs through BOTH hands, so it is centred between them (not on the near hand) ...
        val held = p.at.joint?.startsWith("wrist") == true
        val mid = if (held) V3.lerp(c.gripN, c.gripF, 0.5f) + c.poser.dirToModel(V3(p.at.x, p.at.y, 0f)) * S else c.ref(p.at)
        // ... and its plates sit outside the grip, never between the hands
        val gripHalf = if (held) abs(c.gripN.x - c.gripF.x) / 2f else 0f
        val half = max(0.43f, gripHalf + 0.14f)
        val rad = min(p.r * S * 1.15f, 0.225f)
        out += Prim.Cyl(Kind.CYL_CHROME, mid + V3(-(half + 0.2f), 0f, 0f), mid + V3(half + 0.2f, 0f, 0f), 0.014f)
        for (side in floatArrayOf(-1f, 1f)) {
            for (k in 0..1) {
                val x = side * (half + 0.048f * k)
                out += Prim.Cyl(Kind.CYL_PLATE, mid + V3(x, 0f, 0f), mid + V3(x + side * 0.042f, 0f, 0f), rad * (1f - 0.12f * k))
            }
            out += Prim.Cyl(Kind.CYL_CHROME, mid + V3(side * (half - 0.05f), 0f, 0f), mid + V3(side * half, 0f, 0f), 0.026f)
        }
    }

    private fun dumbbell(p: Prop.Dumbbell, c: Ctx, owned: Set<String>, out: MutableList<Prim>) {
        if (c.slug == "overhead_tricep_extension") {
            // one dumbbell held vertically, both hands cupped under the top plate
            val top = V3.lerp(c.gripN, c.gripF, 0.5f)
            val rad = p.r * S * 1.5f
            out += Prim.Cyl(Kind.CYL_PLATE, top + V3(0f, 0.005f, 0f), top + V3(0f, 0.055f, 0f), rad)
            out += Prim.Cyl(Kind.CYL_CHROME, top + V3(0f, -0.12f, 0f), top + V3(0f, 0.005f, 0f), 0.014f)
            out += Prim.Cyl(Kind.CYL_PLATE, top + V3(0f, -0.17f, 0f), top + V3(0f, -0.12f, 0f), rad)
            return
        }
        val own = p.at.joint
        val refs = ArrayList<Ref>()
        refs += p.at
        // the side view only lists the near hand; the far hand holds one too unless it has its own entry
        mirrorJoint(own ?: "")?.let { m -> if (m !in owned) refs += Ref(m, p.at.x, p.at.y) }
        val rad = p.r * S * 1.25f
        for (r in refs) {
            val at = c.ref(r)
            val ax = c.handAxis(r.joint)
            out += Prim.Cyl(Kind.CYL_CHROME, at - ax * 0.07f, at + ax * 0.07f, 0.014f)
            for (side in floatArrayOf(-1f, 1f)) out += Prim.Cyl(Kind.CYL_PLATE, at + ax * (side * 0.07f), at + ax * (side * 0.125f), rad)
        }
    }

    // ------------------------------------------------------------------------------------------ cables

    private fun cable(p: Prop.Cable, c: Ctx, out: MutableList<Prim>) {
        val from = c.ref(p.from)
        val n = c.gripN; val f = c.gripF
        val apart = (n - f).len() > 0.5f || c.slug == "cable_fly"
        val mid = V3.lerp(n, f, 0.5f)
        val wire = 0.0045f
        when {
            p.grip == "bar" -> {
                // gripF (the far/off-hand) tracks noticeably below the real hand on a close
                // symmetric grip like this - mirroring the near hand across the body's centre
                // line is reliable where gripF isn't, and every "bar" exercise today is a
                // symmetric two-handed grip, so this holds exactly.
                // On a close grip the hand itself sits right against the thigh, so the rod drawn
                // exactly at hand depth clips into the leg - nudge the whole rod forward (the pose's
                // own "forward" axis, not a guessed world axis) clear of the body, and extend it
                // further past each hand so a visible stub of rod actually pokes out of the fist.
                val fwd = c.poser.dirToModel(V3(1f, 0f, 0f)) * (0.035f * S)
                val barN = n + fwd + V3(0f, 0.010f * S, 0f)
                val barF = V3(-barN.x, barN.y, barN.z)
                val barMid = V3.lerp(barN, barF, 0.5f)
                val half = max(abs(barN.x) + 0.1f, 0.16f)
                out += Prim.Cyl(Kind.CYL_CHROME, barMid + V3(-half, 0f, 0f), barMid + V3(half, 0f, 0f), 0.016f)
                out += Prim.Cyl(Kind.CYL_STEEL, from, barMid, wire)
            }
            p.grip == "rope" -> {
                for (h in listOf(n, f)) out += Prim.Cyl(Kind.CYL_BLACK, h + V3(0f, -0.04f, 0f), h + V3(0f, 0.04f, 0f), 0.018f)
                out += Prim.Cyl(Kind.CYL_STEEL, from, mid, wire)
            }
            apart -> {
                // one cable from each side tower to each hand
                for ((h, sx) in listOf(n to -1f, f to 1f)) {
                    out += Prim.Cyl(Kind.CYL_STEEL, V3(sx * 0.62f, from.y, from.z), h, wire)
                    out += Prim.Ball(Kind.SPHERE_STEEL, V3(sx * 0.62f, from.y, from.z), 0.05f)
                    out += Prim.Cyl(Kind.CYL_BLACK, h + V3(0f, -0.045f, 0f), h + V3(0f, 0.045f, 0f), 0.018f)
                }
            }
            else -> {
                out += Prim.Cyl(Kind.CYL_BLACK, mid + V3(-0.07f, 0f, 0f), mid + V3(0.07f, 0f, 0f), 0.016f)
                out += Prim.Cyl(Kind.CYL_STEEL, from, mid, wire)
            }
        }
        if (p.tower) {
            // an open frame (posts + top beam) rather than a solid stack, so it never hides the athlete
            val dir = if (p.from.x >= 0f) 1f else -1f
            val top = from.y + 0.14f * S
            val tz = from.z + dir * 0.1f * S
            val xs = if (apart && p.grip == "handle") floatArrayOf(-0.62f, 0.62f) else floatArrayOf(-0.30f, 0.30f)
            for (sx in xs) out += Prim.Cyl(Kind.CYL_STEEL, V3(sx, 0f, tz), V3(sx, top, tz), 0.03f)
            if (!(apart && p.grip == "handle")) out += Prim.Cyl(Kind.CYL_STEEL, V3(xs[0], top, tz), V3(xs[1], top, tz), 0.03f)
        }
        if (!(apart && p.grip == "handle")) out += Prim.Ball(Kind.SPHERE_STEEL, from, 0.05f)
    }

    // --------------------------------------------------------------------------- discs, rollers, rope

    private fun circle(p: Prop.Circle, c: Ctx, out: MutableList<Prim>) {
        val at = c.ref(p.at)
        val r = p.r * S
        val pinned = p.at.joint != null
        when {
            p.fill && p.role == "metal" && pinned -> {
                // A pinned metal roller (the ankle pad on a leg extension/curl machine) rests
                // against both legs, but was drawn as a fixed +-0.15 cylinder around the near
                // ankle alone - on a wider stance the far leg just hung off the end of it with
                // nothing underneath. Span both ankles instead, centred between them.
                val farJoint = when (p.at.joint) { "ankleN" -> "ankleF"; "ankleF" -> "ankleN"; else -> null }
                val far = farJoint?.let { c.ref(Ref(it, p.at.x, p.at.y)) }
                val mid = if (far != null) V3.lerp(at, far, 0.5f) else at
                val half = if (far != null) max(abs(at.x - far.x) / 2f + 0.08f, 0.15f) else 0.15f
                out += Prim.Cyl(Kind.CYL_BLACK, mid + V3(-half, 0f, 0f), mid + V3(half, 0f, 0f), r * 1.3f)
            }
            p.fill && p.role == "metal" -> out += Prim.Cyl(Kind.CYL_CHROME, at + V3(-0.11f, 0f, 0f), at + V3(0.11f, 0f, 0f), max(r, 0.03f))
            p.fill -> out += Prim.Cyl(Kind.CYL_STEEL, at + V3(-0.06f, 0f, 0f), at + V3(0.06f, 0f, 0f), r)
            else -> out += Prim.Cyl(Kind.CYL_STEEL, at + V3(-0.03f, 0f, 0f), at + V3(0.03f, 0f, 0f), r)
        }
    }

    private fun rope(p: Prop.RopeLoop, c: Ctx, out: MutableList<Prim>) {
        val hand = c.ref(p.at)
        val cy = hand.y / 2f
        val rx = p.rx * S
        // an ellipse in the side-view plane (model Y/Z) from hand down to the floor
        val steps = 22
        var prev: V3? = null
        for (i in 0..steps) {
            val a = PI.toFloat() * 2f * i / steps
            val pt = V3(0f, cy + cos(a) * cy, hand.z + sin(a) * rx)
            prev?.let { out += Prim.Cyl(Kind.CYL_ACCENT, it, pt, 0.006f) }
            prev = pt
        }
        for (h in listOf(c.gripN, c.gripF)) out += Prim.Cyl(Kind.CYL_BLACK, h + V3(0f, -0.055f, 0f), h + V3(0f, 0.055f, 0f), 0.017f)
    }
}
