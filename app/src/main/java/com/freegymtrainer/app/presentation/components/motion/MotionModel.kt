/*
 * Data model + kinematics for the built-in exercise animations.
 *
 * Every exercise is a short list of key poses described by joint angles/targets (see
 * assets/exercise_motions.json, generated by tools/exercise_motion/). At runtime the poses are
 * interpolated and turned into a 2D skeleton (forward kinematics for angle-driven limbs,
 * two-bone IK for target-driven limbs), then drawn as vector art by ExerciseMotionCanvas. It is
 * all original, procedurally drawn artwork - no photos, video or third-party footage - so there
 * is nothing to license, and it adds well under 100 KB to the app.
 *
 * World space: a standing figure is ~1.0 tall, +x is the way the figure faces, +y is up, the
 * floor is y = 0. Angles are compass bearings in degrees (0 = up, 90 = forward, 180 = down).
 * This mirrors tools/exercise_motion/engine.py exactly - change both together.
 */

internal const val THIGH = 0.245f
internal const val SHIN = 0.245f
internal const val TORSO = 0.30f
internal const val UARM = 0.165f
internal const val FARM = 0.185f
internal const val FOOT = 0.10f
internal const val HEAD_D = 0.115f
internal const val HEAD_R = 0.062f

data class Pt(val x: Float, val y: Float) {
    operator fun plus(o: Pt) = Pt(x + o.x, y + o.y)
    operator fun minus(o: Pt) = Pt(x - o.x, y - o.y)
    operator fun times(k: Float) = Pt(x * k, y * k)
}

internal fun vec(deg: Float): Pt {
    val r = Math.toRadians(deg.toDouble())
    return Pt(sin(r).toFloat(), cos(r).toFloat())
}

private fun lerp(a: Float, b: Float, t: Float) = a + (b - a) * t

internal enum class LimbKind { LEG_IK, LEG_FK, ARM_ABS, ARM_SHOULDER, ARM_HIP, ARM_FK }

/**
 * One limb's pose. [v] layout depends on [kind]:
 * LEG_IK [ankleX, ankleY, bend, footBearing]; LEG_FK [thighBearing, shinBearing, footBearing];
 * ARM_ABS/ARM_SHOULDER/ARM_HIP [x, y, bend] (hand target: world / relative to shoulder / relative
 * to hip); ARM_FK [upperBearing, forearmBearing, relativeToTorso(0/1), lengthScale].
 */
internal class Limb(val kind: LimbKind, val v: FloatArray)

private fun lerpLimb(a: Limb, b: Limb, t: Float): Limb {
    // Authoring tool guarantees both keys of a limb use the same kind.
    val out = FloatArray(a.v.size) { i -> lerp(a.v[i], b.v.getOrElse(i) { a.v[i] }, t) }
    return Limb(a.kind, out)
}

/**
 * What the side-view data cannot say, needed by the 3D view: how far each limb swings out to the side
 * (degrees, 0 = stays in the plane of the movement), how wide the hands are held on a bar ([grip],
 * half-distance in world units, 0 = natural) and how wide the feet are placed ([stance], same units).
 */
internal class Lateral(
    val armN: Float = 0f, val armF: Float = 0f, val legN: Float = 0f, val legF: Float = 0f,
    val grip: Float = 0f, val stance: Float = 0f
) {
    companion object { val NONE = Lateral() }
}

private fun lerpLateral(a: Lateral, b: Lateral, t: Float) = Lateral(
    lerp(a.armN, b.armN, t), lerp(a.armF, b.armF, t), lerp(a.legN, b.legN, t), lerp(a.legF, b.legF, t),
    lerp(a.grip, b.grip, t), lerp(a.stance, b.stance, t)
)

internal class KeyPose(
    val t: Float,
    val hipX: Float, val hipY: Float,
    val torso: Float, val head: Float, val spine: Float, val shoulderLift: Float,
    val legN: Limb, val legF: Limb, val armN: Limb, val armF: Limb,
    val label: String, val cue: String,
    val lateral: Lateral = Lateral.NONE
)

/** A point in a prop's geometry: either fixed in the world or pinned to a joint (+ offset). */
internal class Ref(val joint: String?, val x: Float, val y: Float)

internal sealed class Prop(val z: Int) {
    class Line(val a: Ref, val b: Ref, val w: Float, val role: String, z: Int) : Prop(z)
    class Circle(val at: Ref, val r: Float, val role: String, val fill: Boolean, z: Int) : Prop(z)
    class Plate(val at: Ref, val r: Float, z: Int) : Prop(z)
    class Dumbbell(val at: Ref, val r: Float, z: Int) : Prop(z)
    class Cable(val from: Ref, val at: Ref, val grip: String, val tower: Boolean, z: Int) : Prop(z)
    class RopeLoop(val at: Ref, val rx: Float, z: Int) : Prop(z)
}

internal class Measure(val name: String, val joints: List<String>) {
    val isLean get() = joints.size == 1
}

class MotionDef internal constructor(
    internal val keys: List<KeyPose>,
    internal val props: List<Prop>,
    internal val measures: List<Measure>,
    internal val focus: List<String>,
    val durationMs: Int,
    private val smooth: Boolean,
    internal val view: FloatArray?,
    val tip: String,
    /** The movement happens in the plane facing the viewer (Warrior II, Lateral Raise ...), not the side plane. */
    val frontal: Boolean = false
) {
    val keyTimes: List<Float> get() = keys.map { it.t }

    /** Index of the key pose that is "current" at [progress] (0..1) - used for the phase caption. */
    fun phaseIndex(progress: Float): Int {
        var idx = 0
        for (i in keys.indices) if (keys[i].t <= progress + 1e-6f) idx = i
        return idx
    }

    fun phaseLabel(index: Int) = keys[index].label
    fun phaseCue(index: Int) = keys[index].cue
    val hasMeasures get() = measures.isNotEmpty()

    /**
     * Camera rectangle [minX, maxX, minY, maxY] that frames the whole movement: the bounding box of
     * every joint and prop over the full cycle, plus the floor. Computed once per exercise so each
     * animation fills its frame instead of relying on hand-tuned numbers.
     */
    internal val frame: FloatArray by lazy {
        var minX = Float.MAX_VALUE; var maxX = -Float.MAX_VALUE
        var minY = 0f; var maxY = 0f
        fun add(p: Pt, clampTop: Boolean = false) {
            val y = if (clampTop) min(p.y, 1.35f) else p.y
            minX = min(minX, p.x); maxX = max(maxX, p.x); minY = min(minY, y); maxY = max(maxY, y)
        }
        for (i in 0 until 40) {
            val sk = skeletonAt(i / 40f)
            listOf(sk.hip, sk.shoulder, sk.kneeN, sk.ankleN, sk.toeN, sk.kneeF, sk.ankleF, sk.toeF, sk.elbowN, sk.wristN, sk.elbowF, sk.wristF)
                .forEach { add(it) }
            add(Pt(sk.head.x - HEAD_R, sk.head.y - HEAD_R)); add(Pt(sk.head.x + HEAD_R, sk.head.y + HEAD_R))
            for (p in props) when (p) {
                is Prop.Line -> {
                    val a = sk.resolve(p.a); val b = sk.resolve(p.b)
                    // Floor mats/lines run far beyond the figure; they shouldn't shrink it.
                    if (!(a.y < 0.05f && b.y < 0.05f)) { add(a, true); add(b, true) }
                }
                is Prop.Circle -> sk.resolve(p.at).let { c -> add(Pt(c.x - p.r, c.y - p.r), true); add(Pt(c.x + p.r, c.y + p.r), true) }
                is Prop.Plate -> sk.resolve(p.at).let { c -> add(Pt(c.x - p.r, c.y - p.r), true); add(Pt(c.x + p.r, c.y + p.r), true) }
                is Prop.Dumbbell -> sk.resolve(p.at).let { c -> add(Pt(c.x - p.r, c.y - p.r), true); add(Pt(c.x + p.r, c.y + p.r), true) }
                is Prop.RopeLoop -> sk.resolve(p.at).let { c -> add(Pt(c.x - p.rx, 0f)); add(Pt(c.x + p.rx, c.y)) }
                is Prop.Cable -> {
                    val f = sk.resolve(p.from)
                    add(sk.resolve(p.at))
                    add(f, true)
                    if (p.tower) {
                        val dir = if (f.x >= 0f) 1f else -1f
                        add(Pt(f.x + dir * 0.23f, 0f)); add(Pt(f.x + dir * 0.23f, f.y + 0.14f), true)
                    }
                }
            }
        }
        // Breathing room: extra on top for the angle readout / "side view" tag.
        floatArrayOf(minX - 0.12f, maxX + 0.12f, minY - 0.07f, maxY + 0.16f)
    }

    /** Dotted path of the joint that travels furthest in a rep (the bar path); empty for holds. */
    internal val trail: List<Pt> by lazy { computeTrail() }

    internal fun skeletonAt(progress: Float): Skeleton {
        val p = ((progress % 1f) + 1f) % 1f
        var i = 0
        for (k in keys.indices) if (keys[k].t <= p) i = k
        val a = keys[i]
        val bIdx = (i + 1) % keys.size
        val b = keys[bIdx]
        val bT = if (bIdx == 0) 1f else b.t
        val span = bT - a.t
        var u = if (span <= 0f) 0f else (p - a.t) / span
        if (smooth) u = u * u * (3 - 2 * u)
        return resolve(
            hipX = lerp(a.hipX, b.hipX, u), hipY = lerp(a.hipY, b.hipY, u),
            torso = lerp(a.torso, b.torso, u), head = lerp(a.head, b.head, u),
            spine = lerp(a.spine, b.spine, u), shoulderLift = lerp(a.shoulderLift, b.shoulderLift, u),
            legN = lerpLimb(a.legN, b.legN, u), legF = lerpLimb(a.legF, b.legF, u),
            armN = lerpLimb(a.armN, b.armN, u), armF = lerpLimb(a.armF, b.armF, u),
            lateral = lerpLateral(a.lateral, b.lateral, u)
        )
    }
}

/** Resolved joint positions for one instant. N = near side (drawn in front), F = far side. */
internal class Skeleton(
    val hip: Pt, val shoulder: Pt, val head: Pt, val torso: Float, val spine: Float,
    val kneeN: Pt, val ankleN: Pt, val toeN: Pt, val kneeF: Pt, val ankleF: Pt, val toeF: Pt,
    val elbowN: Pt, val wristN: Pt, val elbowF: Pt, val wristF: Pt,
    val lateral: Lateral = Lateral.NONE
) {
    fun point(name: String): Pt = when (name) {
        "hip" -> hip
        "shoulder" -> shoulder
        "head" -> head
        "kneeN" -> kneeN
        "ankleN" -> ankleN
        "toeN" -> toeN
        "kneeF" -> kneeF
        "ankleF" -> ankleF
        "toeF" -> toeF
        "elbowN" -> elbowN
        "wristN" -> wristN
        "elbowF" -> elbowF
        "wristF" -> wristF
        else -> hip
    }

    fun resolve(ref: Ref): Pt =
        if (ref.joint == null) Pt(ref.x, ref.y) else point(ref.joint) + Pt(ref.x, ref.y)

    /** Interior angle (degrees) at joint [b] between segments b->a and b->c, or torso lean for "lean". */
    fun measure(m: Measure): Float {
        if (m.isLean) {
            val d = ((torso + 180f) % 360f + 360f) % 360f - 180f
            return kotlin.math.abs(d)
        }
        val a = point(m.joints[0]); val b = point(m.joints[1]); val c = point(m.joints[2])
        val v1 = a - b; val v2 = c - b
        val n = hypot(v1.x, v1.y) * hypot(v2.x, v2.y)
        if (n == 0f) return 0f
        val cosA = ((v1.x * v2.x + v1.y * v2.y) / n).coerceIn(-1f, 1f)
        return Math.toDegrees(acos(cosA).toDouble()).toFloat()
    }
}

/** Two-bone IK. Returns (mid joint, end point). bend = +1 rotates the mid joint counter-clockwise of the root->target line. */
private fun ik(root: Pt, target: Pt, l1: Float, l2: Float, bend: Float): Pair<Pt, Pt> {
    val dx = target.x - root.x
    val dy = target.y - root.y
    val d = min(max(hypot(dx, dy), kotlin.math.abs(l1 - l2) + 1e-4f), l1 + l2 - 1e-4f)
    val bearing = Math.toDegrees(atan2(dx.toDouble(), dy.toDouble())).toFloat()
    val cosA = ((l1 * l1 + d * d - l2 * l2) / (2 * l1 * d)).coerceIn(-1f, 1f)
    val a = Math.toDegrees(acos(cosA).toDouble()).toFloat()
    val mid = root + vec(bearing - bend * a) * l1
    val end = root + vec(bearing) * d
    return mid to end
}

private class Leg(val knee: Pt, val ankle: Pt, val toe: Pt)

private fun resolveLeg(hip: Pt, limb: Limb): Leg {
    val v = limb.v
    return if (limb.kind == LimbKind.LEG_IK) {
        val (knee, ankle) = ik(hip, Pt(v[0], v[1]), THIGH, SHIN, v[2])
        Leg(knee, ankle, ankle + vec(v[3]) * FOOT)
    } else {
        val knee = hip + vec(v[0]) * THIGH
        val ankle = knee + vec(v[1]) * SHIN
        Leg(knee, ankle, ankle + vec(v[2]) * FOOT)
    }
}

private fun resolveArm(shoulder: Pt, hip: Pt, torso: Float, limb: Limb): Pair<Pt, Pt> {
    val v = limb.v
    return when (limb.kind) {
        LimbKind.ARM_FK -> {
            val rt = if (v[2] > 0.5f) torso else 0f
            val sc = v[3]
            val elbow = shoulder + vec(v[0] + rt) * (UARM * sc)
            elbow to (elbow + vec(v[1] + rt) * (FARM * sc))
        }
        else -> {
            val target = when (limb.kind) {
                LimbKind.ARM_ABS -> Pt(v[0], v[1])
                LimbKind.ARM_SHOULDER -> shoulder + Pt(v[0], v[1])
                else -> hip + Pt(v[0], v[1])
            }
            ik(shoulder, target, UARM, FARM, v[2])
        }
    }
}

internal fun resolve(
    hipX: Float, hipY: Float, torso: Float, head: Float, spine: Float, shoulderLift: Float,
    legN: Limb, legF: Limb, armN: Limb, armF: Limb,
    lateral: Lateral = Lateral.NONE
): Skeleton {
    val hip = Pt(hipX, hipY)
    val shoulder = hip + vec(torso) * TORSO + Pt(0f, shoulderLift)
    val headPt = shoulder + vec(torso + head) * HEAD_D
    val ln = resolveLeg(hip, legN)
    val lf = resolveLeg(hip, legF)
    val (elbowN, wristN) = resolveArm(shoulder, hip, torso, armN)
    val (elbowF, wristF) = resolveArm(shoulder, hip, torso, armF)
    return Skeleton(
        hip, shoulder, headPt, torso, spine,
        ln.knee, ln.ankle, ln.toe, lf.knee, lf.ankle, lf.toe,
        elbowN, wristN, elbowF, wristF, lateral
    )
}

// ---------------------------------------------------------------------------- JSON parsing

private fun JSONObject.floatOr(name: String, default: Float) = if (has(name)) getDouble(name).toFloat() else default

private fun JSONArray.floats(): FloatArray = FloatArray(length()) { getDouble(it).toFloat() }

private fun parseLimb(o: JSONObject, leg: Boolean): Limb =
    if (leg) {
        if (o.has("a")) {
            val a = o.getJSONArray("a").floats()
            Limb(LimbKind.LEG_IK, floatArrayOf(a[0], a[1], o.floatOr("b", 1f), o.floatOr("ft", 90f)))
        } else {
            Limb(LimbKind.LEG_FK, floatArrayOf(o.getDouble("th").toFloat(), o.getDouble("sh").toFloat(), o.floatOr("ft", 90f)))
        }
    } else {
        val bend = o.floatOr("b", -1f)
        when {
            o.has("h") -> o.getJSONArray("h").floats().let { Limb(LimbKind.ARM_ABS, floatArrayOf(it[0], it[1], bend)) }
            o.has("hs") -> o.getJSONArray("hs").floats().let { Limb(LimbKind.ARM_SHOULDER, floatArrayOf(it[0], it[1], bend)) }
            o.has("hh") -> o.getJSONArray("hh").floats().let { Limb(LimbKind.ARM_HIP, floatArrayOf(it[0], it[1], bend)) }
            else -> Limb(
                LimbKind.ARM_FK,
                floatArrayOf(o.getDouble("u").toFloat(), o.getDouble("f").toFloat(), if (o.has("rt")) 1f else 0f, o.floatOr("sc", 1f))
            )
        }
    }

private fun parseRef(any: Any): Ref = when (any) {
    is String -> Ref(any, 0f, 0f)
    is JSONArray -> Ref(null, any.getDouble(0).toFloat(), any.getDouble(1).toFloat())
    is JSONObject -> {
        val off = any.optJSONArray("off")
        Ref(any.getString("p"), off?.getDouble(0)?.toFloat() ?: 0f, off?.getDouble(1)?.toFloat() ?: 0f)
    }
    else -> Ref(null, 0f, 0f)
}

private fun parseProp(o: JSONObject): Prop? {
    val z = o.optInt("z", 0)
    val role = o.optString("c", "furn")
    return when (o.getString("k")) {
        "line" -> Prop.Line(parseRef(o.get("a")), parseRef(o.get("b")), o.floatOr("w", 0.03f), role, z)
        "circle" -> Prop.Circle(parseRef(o.get("at")), o.getDouble("r").toFloat(), role, o.optBoolean("fill", true), z)
        "plate" -> Prop.Plate(parseRef(o.get("at")), o.floatOr("r", 0.085f), z)
        "db" -> Prop.Dumbbell(parseRef(o.get("at")), o.floatOr("r", 0.045f), z)
        "cable" -> Prop.Cable(parseRef(o.get("from")), parseRef(o.get("at")), o.optString("g", "handle"), o.optBoolean("tower", true), z)
        "ropeloop" -> Prop.RopeLoop(parseRef(o.get("at")), o.floatOr("rx", 0.2f), z)
        else -> null
    }
}

/** Optional "lat": [armN, armF, legN, legF] degrees, "grip" and "stance" half-widths (see [Lateral]). */
private fun parseLateral(k: JSONObject): Lateral {
    val lat = k.optJSONArray("lat")?.floats()
    if (lat == null && !k.has("grip") && !k.has("stance")) return Lateral.NONE
    fun at(i: Int) = lat?.getOrNull(i) ?: 0f
    return Lateral(
        armN = at(0), armF = if (lat != null && lat.size > 1) lat[1] else at(0),
        legN = at(2), legF = if (lat != null && lat.size > 3) lat[3] else at(2),
        grip = k.floatOr("grip", 0f), stance = k.floatOr("stance", 0f)
    )
}

private fun parseMotion(o: JSONObject): MotionDef {
    val keysJson = o.getJSONArray("keys")
    val keys = (0 until keysJson.length()).map { i ->
        val k = keysJson.getJSONObject(i)
        val hip = k.getJSONArray("hip").floats()
        val legN = parseLimb(k.getJSONObject("legN"), true)
        val armN = parseLimb(k.getJSONObject("armN"), false)
        KeyPose(
            t = k.getDouble("t").toFloat(),
            hipX = hip[0], hipY = hip[1],
            torso = k.getDouble("T").toFloat(), head = k.floatOr("head", 0f),
            spine = k.floatOr("spine", 0f), shoulderLift = k.floatOr("sl", 0f),
            legN = legN, legF = if (k.has("legF")) parseLimb(k.getJSONObject("legF"), true) else legN,
            armN = armN, armF = if (k.has("armF")) parseLimb(k.getJSONObject("armF"), false) else armN,
            label = k.optString("label", ""), cue = k.optString("cue", ""),
            lateral = parseLateral(k)
        )
    }
    val propsJson = o.optJSONArray("props") ?: JSONArray()
    val props = (0 until propsJson.length()).mapNotNull { parseProp(propsJson.getJSONObject(it)) }
    val measuresJson = o.optJSONArray("measure") ?: JSONArray()
    val measures = (0 until measuresJson.length()).map { i ->
        val m = measuresJson.getJSONObject(i)
        val j = m.getJSONArray("j")
        Measure(m.getString("name"), (0 until j.length()).map { j.getString(it) })
    }
    val focusJson = o.optJSONArray("focus") ?: JSONArray()
    return MotionDef(
        keys = keys,
        props = props,
        measures = measures,
        focus = (0 until focusJson.length()).map { focusJson.getString(it) },
        durationMs = o.optInt("dur", 3000),
        smooth = o.optString("ease", "smooth") == "smooth",
        view = o.optJSONArray("view")?.floats(),
        tip = o.optString("tip", ""),
        frontal = o.optBoolean("frontal", false)
    )
}

/** Loads `assets/exercise_motions.json` once and serves motions by exercise slug. */
object ExerciseMotionLibrary {
    @Volatile
    private var motions: Map<String, MotionDef>? = null

    /** Safe to call from a background thread at startup so the first exercise screen opens instantly. */
    fun preload(context: Context) {
        load(context.applicationContext)
    }

    fun forExerciseName(context: Context, exerciseName: String): MotionDef? =
        load(context.applicationContext)[exerciseSlug(exerciseName)]

    private fun load(context: Context): Map<String, MotionDef> {
        motions?.let { return it }
        synchronized(this) {
            motions?.let { return it }
            val parsed = try {
                val text = context.assets.open("exercise_motions.json").bufferedReader().use { it.readText() }
                val root = JSONObject(text)
                buildMap<String, MotionDef> {
                    for (name in root.keys()) {
                        // One malformed entry must never take the whole library (or the app) down.
                        try {
                            put(exerciseSlug(name), parseMotion(root.getJSONObject(name)))
                        } catch (e: Exception) {
                            android.util.Log.w("ExerciseMotion", "Skipping bad motion '$name'", e)
                        }
                    }
                }
            } catch (e: IOException) {
                emptyMap()
            } catch (e: org.json.JSONException) {
                emptyMap()
            }
            motions = parsed
            return parsed
        }
    }
}
